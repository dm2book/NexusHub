#!/usr/bin/env node
/**
 * Write down every piece of product art this repo actually ships.
 *
 *   node scripts/gen-art-manifest.mjs        # regenerate src/lib/shippedArt.js
 *   node scripts/gen-art-manifest.mjs --check  # fail if it is out of date
 *
 * Why a generated list instead of asking the filesystem?
 *
 * Because the code that most needs the answer cannot ask. `public/` is copied
 * into the static output and served by the CDN; it is NOT part of the
 * serverless function's bundle, so `fs.existsSync('/products/icons/robux.webp')`
 * inside the API is false in production for a file that loads perfectly in a
 * browser. A launch check built on that would call the whole catalogue broken.
 *
 * So the truth is committed as a module the function imports like any other,
 * and a test compares it back to the real directory — the drift this file could
 * introduce is exactly the drift that test refuses to let land.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'public', 'products');
const OUT = path.join(ROOT, 'src', 'lib', 'shippedArt.js');

const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
  const full = path.join(dir, e.name);
  return e.isDirectory() ? walk(full) : [full];
});

const paths = walk(DIR)
  .filter((f) => /\.(svg|webp|png|jpe?g|avif)$/i.test(f))
  .map((f) => '/' + path.relative(path.join(ROOT, 'public'), f).split(path.sep).join('/'))
  .sort();

const body = `/**
 * Every product image this repo ships, as served paths.
 *
 * GENERATED by scripts/gen-art-manifest.mjs — do not edit by hand. Add a file
 * to public/products/ and re-run it; server/test/product-art.test.mjs fails
 * while this list and that directory disagree.
 *
 * It exists so code that runs where public/ is not on disk — the serverless
 * API — can still answer "does this product's picture exist?".
 */
export const SHIPPED_ART = new Set([
${paths.map((p) => `  '${p}',`).join('\n')}
]);

/**
 * Does this image source resolve to something?
 *
 * Returns 'ok' | 'missing' | 'remote' | 'uploaded' | 'none'. Remote links and
 * data-URI uploads are the owner's own; we can say they are set, not that they
 * still load, and pretending otherwise would be the more expensive lie.
 */
export function artStatus(src) {
  if (!src || typeof src !== 'string') return 'none';
  if (src.startsWith('data:')) return 'uploaded';
  if (/^https?:/i.test(src)) return 'remote';
  return SHIPPED_ART.has(src.split('?')[0]) ? 'ok' : 'missing';
}
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== body) {
    console.error('src/lib/shippedArt.js is out of date — run: node scripts/gen-art-manifest.mjs');
    process.exit(1);
  }
  console.log(`shippedArt.js is current (${paths.length} files).`);
} else {
  fs.writeFileSync(OUT, body);
  console.log(`Wrote ${paths.length} art paths to src/lib/shippedArt.js`);
}
