#!/usr/bin/env node
/**
 * The bot's copy of "how is this delivered", generated from the shop's.
 *
 *   node scripts/gen-discord-delivery.mjs            write it
 *   node scripts/gen-discord-delivery.mjs --check    fail if it is stale
 *
 * The bot ships as its own Docker image whose Dockerfile does `COPY . .` from
 * discord/, so that tree cannot import src/lib — the same constraint that gave
 * BANNER_VERSION a checked duplicate. A duplicate is only safe while something
 * regenerates it and something else fails when it drifts; this is the first
 * half and discord/test/delivery.test.mjs is the second.
 *
 * What it replaces: discord/src/config.js carried its own DELIVERY_INFO with
 * two categories and a comment promising it was "kept in step with
 * src/lib/deliveryInfo.js". Both had two. The shop sells twenty-one, and the
 * recipes for eight of them were already written, already translated, and
 * reachable only from the delivery email.
 */
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = process.cwd();
const OUT = path.join(ROOT, 'discord', 'src', 'generated', 'delivery.js');
const LANGS = ['nl', 'en', 'de', 'fr'];

const { deliveryInfo, deliveryCategories, deliveryField } =
  await import(pathToFileURL(path.join(ROOT, 'src/lib/deliveryInfo.js')).href);

const cats = deliveryCategories();
const table = {};
for (const lang of LANGS) {
  table[lang] = {};
  for (const cat of [...cats, 'default']) {
    const d = deliveryInfo(cat === 'default' ? '__none__' : cat, lang);
    table[lang][cat] = { method: d.method, steps: d.steps, notes: d.notes };
  }
}
const fields = {};
for (const cat of cats) {
  const per = {};
  for (const lang of LANGS) { const f = deliveryField(cat, lang); if (f) per[lang] = f; }
  if (Object.keys(per).length) fields[cat] = per;
}

const body = `/**
 * GENERATED by scripts/gen-discord-delivery.mjs — do not edit by hand.
 *
 * The same answers the product page gives, in the same four languages. The bot
 * cannot import src/lib (its Docker image copies only discord/), so this is a
 * checked copy: regenerate with \`node scripts/gen-discord-delivery.mjs\` and
 * discord/test/delivery.test.mjs fails while this file and the shop disagree.
 */
export const DELIVERY = ${JSON.stringify(table, null, 2)};

/** The one thing the buyer has to hand over for this category, or null. */
export const DELIVERY_FIELD = ${JSON.stringify(fields, null, 2)};

/** Categories this shop can answer specifically rather than generically. */
export const DELIVERY_CATEGORIES = ${JSON.stringify(cats)};

/** One category, one language, never undefined in front of a member. */
export function deliveryFor(category, lang = 'en') {
  const table = DELIVERY[lang] || DELIVERY.en;
  return table[String(category || '').toLowerCase()] || table.default;
}
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== body) {
    console.error('discord/src/generated/delivery.js is out of date — run: node scripts/gen-discord-delivery.mjs');
    process.exit(1);
  }
  console.log(`delivery.js is current (${cats.length} categories x ${LANGS.length} languages).`);
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, body);
  console.log(`Wrote ${cats.length} categories x ${LANGS.length} languages to discord/src/generated/delivery.js`);
}
