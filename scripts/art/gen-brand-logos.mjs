#!/usr/bin/env node
/**
 * Real brand logos for the product cards, from Simple Icons.
 *
 *   node scripts/art/gen-brand-logos.mjs           write server/src/generated/brandLogos.js
 *   node scripts/art/gen-brand-logos.mjs --check   exit 1 when it is out of date
 *
 * ── WHERE THEY COME FROM ─────────────────────────────────────────────────
 * Simple Icons (simpleicons.org, npm "simple-icons", pinned in devDependencies)
 * publishes each brand's official mark as a single SVG path with the brand's
 * own colour, under CC0 — no copyright duty on the drawing. The marks remain
 * their owners' trademarks: showing the brand of the gift card or currency the
 * shop sells is nominative use, and every product page already says the shop is
 * not affiliated. Brands that asked to be removed from Simple Icons (Xbox,
 * Nintendo, Amazon, …) are not in it, and are not taken from anywhere else:
 * those cards keep their drawn mark.
 *
 * Only the brands this shop sells are generated, mapped from the card's own
 * slug (category or brandSlug) to the Simple Icons slug. Nothing is fetched at
 * runtime; the module travels with the server like artAssets.js.
 */
import fs from 'node:fs';
import path from 'node:path';
import * as SI from 'simple-icons';

const ROOT = process.cwd();
const OUT = path.join(ROOT, 'server', 'src', 'generated', 'brandLogos.js');

/* card slug → [Simple Icons slug, how the card uses it]
   'hero'  — a service whose mark IS the product (Spotify, Twitch): drawn as an
             app icon in the brand's colour.
   'badge' — a game or store: the mark sits small beside the name, the
             currency or card art stays the hero. */
const MAP = {
  spotify: ['spotify', 'hero'], twitch: ['twitch', 'hero'], crunchyroll: ['crunchyroll', 'hero'],
  'discord-nitro': ['discord', 'badge'], netflix: ['netflix', 'badge'], googleplay: ['googleplay', 'badge'],
  itunes: ['apple', 'badge'], playstation: ['playstation', 'badge'], steam: ['steam', 'badge'],
  robux: ['roblox', 'badge'], 'v-bucks': ['fortnite', 'badge'], league: ['leagueoflegends', 'badge'],
  valorant: ['valorant', 'badge'], pubg: ['pubg', 'badge'], gta: ['rockstargames', 'badge'],
  eafc: ['ea', 'badge'], apex: ['ea', 'badge'],
  /* Not Activision (COD) or Supercell (Brawl Stars, Clash): wordmarks, and at
     badge size a wordmark is an unreadable smudge. Those cards keep the name. */
  dota: ['dota2', 'badge'], csgo: ['counterstrike', 'badge'], battlenet: ['battledotnet', 'badge'],
  epicgames: ['epicgames', 'badge'], ubisoft: ['ubisoft', 'badge'],
  /* miHoYo (Genshin, Honkai) is a wordmark as well — left out for the same reason. */
};

/* The Logo Library's own set (logoDiscoveryService.js): every one of the 21
   brands the shop tracks that Simple Icons has, as a complete SVG in the
   brand's colour — tier "public SVG" there, never fetched at runtime. */
const LIBRARY_SLUGS = {
  roblox: 'roblox', valorant: 'valorant', riot: 'riotgames', league: 'leagueoflegends', steam: 'steam',
  playstation: 'playstation', eafc: 'ea', fortnite: 'fortnite', epic: 'epicgames', discord: 'discord',
  spotify: 'spotify', netflix: 'netflix', crunchyroll: 'crunchyroll', googleplay: 'googleplay', apple: 'apple',
  blizzard: 'battledotnet',
};

function build() {
  const bySlug = Object.fromEntries(Object.values(SI).filter((x) => x && x.slug).map((x) => [x.slug, x]));
  const logos = {};
  for (const [card, [slug, role]] of Object.entries(MAP)) {
    const icon = bySlug[slug];
    if (!icon) continue;
    logos[card] = { title: icon.title, hex: `#${icon.hex}`, path: icon.path, role, source: `simple-icons/${slug}`, license: 'CC0-1.0',
      ...(icon.guidelines ? { guidelines: icon.guidelines } : {}) };
  }
  const library = {};
  for (const [brand, slug] of Object.entries(LIBRARY_SLUGS)) {
    const icon = bySlug[slug];
    if (!icon) continue;
    library[brand] = { title: icon.title, hex: `#${icon.hex}`, source: `simple-icons/${slug}`, license: 'CC0-1.0',
      sourceUrl: `https://simpleicons.org/?q=${encodeURIComponent(slug)}`,
      ...(icon.guidelines ? { guidelines: icon.guidelines } : {}),
      svg: `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" role="img"><title>${icon.title}</title><path fill="#${icon.hex}" d="${icon.path}"/></svg>` };
  }
  return '/* Generated by scripts/art/gen-brand-logos.mjs from simple-icons (CC0-1.0). Do not edit. */\n'
    + `export const LOGOS = ${JSON.stringify(logos, null, 1)};\n`
    + `export const LIBRARY = ${JSON.stringify(library, null, 1)};\n`;
}

const next = build();
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== next) { console.error('server/src/generated/brandLogos.js is out of date — run: node scripts/art/gen-brand-logos.mjs'); process.exit(1); }
  console.log('brand logos up to date');
} else {
  fs.writeFileSync(OUT, next);
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
}
