#!/usr/bin/env node
/**
 * Bundle the category marks into the server, so a tile drawn at runtime can use
 * the SAME files the shipped artwork was composited from.
 *
 *   node scripts/gen-art-assets.mjs           write server/src/generated/artAssets.js
 *   node scripts/gen-art-assets.mjs --check   exit 1 when it is out of date
 *
 * ── WHY A GENERATED MODULE ────────────────────────────────────────────────
 * The artwork renderer (scripts/art/render.mjs) reads its marks from
 * public/products/icons. On Vercel the API is a function bundle, and public/ is
 * served by the CDN beside it, not shipped inside it — so a tile rendered there
 * could not reach a single mark, and had to fall back to a number on a
 * gradient. Imported as a module, the files travel with the code that needs
 * them, and the bundler cannot leave them behind.
 *
 * Nothing is redrawn: each entry is the file's own bytes. A mark here is the
 * official file already used on 71 shipped boards, not an approximation of it.
 *
 * server/test/art-assets.test.mjs runs --check, so an icon added to public/
 * without regenerating this fails the build instead of shipping a tile that
 * quietly lacks it.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const DIR = path.join(ROOT, 'public', 'products', 'icons');
const OUT = path.join(ROOT, 'server', 'src', 'generated', 'artAssets.js');
const RASTER = { '.webp': 'image/webp', '.png': 'image/png', '.jpg': 'image/jpeg' };

function build() {
  const files = fs.readdirSync(DIR).filter((f) => /\.(svg|webp|png|jpg)$/.test(f)).sort();
  const assets = {};
  for (const f of files) {
    const ext = path.extname(f);
    const src = `/products/icons/${f}`;
    assets[src] = ext === '.svg'
      ? { text: fs.readFileSync(path.join(DIR, f), 'utf8') }
      : { mime: RASTER[ext], b64: fs.readFileSync(path.join(DIR, f)).toString('base64') };
  }
  let ink = {};
  try { ink = JSON.parse(fs.readFileSync(path.join(DIR, '_ink.json'), 'utf8')); } catch { ink = {}; }
  return '/* Generated by scripts/gen-art-assets.mjs from public/products/icons. Do not edit. */\n'
    + `export const ASSETS = ${JSON.stringify(assets)};\n`
    + `export const INK = ${JSON.stringify(ink)};\n`;
}

const next = build();
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== next) {
    console.error('server/src/generated/artAssets.js is out of date — run: node scripts/gen-art-assets.mjs');
    process.exit(1);
  }
  console.log('art assets up to date');
} else {
  fs.writeFileSync(OUT, next);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${(next.length / 1024).toFixed(0)} KB)`);
}
